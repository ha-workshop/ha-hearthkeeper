"""Voice input and output for Hearthkeeper.

Incoming audio is decoded with ``ffmpeg`` into the format every Assist speech
engine understands (WAV, 16 kHz, mono, 16 bit) and fed into the Assist pipeline,
which runs the pipeline's own STT, conversation agent and language settings.

Outgoing audio is generated by the pipeline's TTS engine, encoded to OGG/Opus
for a Telegram voice note and staged just long enough for ``telegram_bot`` to
read it. Nothing is written to disk for longer than one reply.
"""

from __future__ import annotations

import asyncio
import logging
import shutil
import uuid
from collections.abc import AsyncIterator
from dataclasses import dataclass
from pathlib import Path

from homeassistant.core import Context, HomeAssistant, callback
from homeassistant.exceptions import HomeAssistantError

from .assist import PipelineSettings, extract_speech
from .const import (
    MEDIA_TIMEOUT,
    STORAGE_DIR,
    TTS_TIMEOUT,
    VOICE_SAMPLE_RATE,
    VOICE_TIMEOUT,
)
from .transport import Attachment

_LOGGER = logging.getLogger(__name__)

_AUDIO_SUFFIXES: dict[str, str] = {
    "audio/ogg": ".ogg",
    "audio/opus": ".ogg",
    "audio/mpeg": ".mp3",
    "audio/mp3": ".mp3",
    "audio/mp4": ".m4a",
    "audio/x-m4a": ".m4a",
    "audio/aac": ".aac",
    "audio/wav": ".wav",
    "audio/x-wav": ".wav",
    "audio/wave": ".wav",
    "audio/webm": ".webm",
    "audio/flac": ".flac",
    "audio/x-flac": ".flac",
}

_AUDIO_EXTENSIONS: dict[str, str] = {
    ".ogg": ".ogg",
    ".oga": ".ogg",
    ".opus": ".ogg",
    ".mp3": ".mp3",
    ".m4a": ".m4a",
    ".aac": ".aac",
    ".wav": ".wav",
    ".webm": ".webm",
    ".flac": ".flac",
}

_CHUNK_SIZE = 8192


class VoiceTooLongError(HomeAssistantError):
    """The voice message is longer than the configured limit."""


class VoiceNotConfiguredError(HomeAssistantError):
    """The pipeline cannot handle one side of the voice conversation."""


@dataclass(frozen=True, slots=True)
class PipelineReply:
    """What the Assist pipeline returned for one audio message."""

    text: str
    conversation_id: str | None = None


def audio_suffix(attachment: Attachment | None) -> str | None:
    """Return the file suffix when the attachment is audio, else ``None``."""
    if attachment is None:
        return None

    mime = (attachment.mime_type or "").split(";", 1)[0].strip().lower()
    if mime.startswith("audio/"):
        return _AUDIO_SUFFIXES.get(mime, _extension(attachment.file_name) or ".ogg")

    if mime in ("application/ogg", "application/octet-stream", ""):
        return _extension(attachment.file_name)

    return None


def is_audio(attachment: Attachment | None) -> bool:
    """Return True when the attachment is an audio message."""
    return audio_suffix(attachment) is not None


def _extension(file_name: str | None) -> str | None:
    """Return a known audio suffix of a file name."""
    if not file_name:
        return None
    return _AUDIO_EXTENSIONS.get(Path(file_name).suffix.lower())


async def async_transcode_to_wav(
    hass: HomeAssistant,
    source: Path,
    *,
    max_seconds: int,
) -> bytes:
    """Decode any Telegram audio into WAV 16 kHz mono PCM.

    Raises ``VoiceTooLongError`` when the message exceeds ``max_seconds`` and
    ``HomeAssistantError`` when decoding fails.
    """
    if max_seconds > 0:
        duration = await _async_duration(hass, source)
        if duration is not None and duration > max_seconds:
            raise VoiceTooLongError("voice message is too long")

    ffmpeg = await _async_which(hass, "ffmpeg")
    if ffmpeg is None:
        raise HomeAssistantError("ffmpeg is not installed")

    wav = await _async_run(
        ffmpeg,
        [
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(source),
            "-vn",
            "-ac",
            "1",
            "-ar",
            str(VOICE_SAMPLE_RATE),
            "-c:a",
            "pcm_s16le",
            "-f",
            "wav",
            "pipe:1",
        ],
    )
    if not wav:
        raise HomeAssistantError("ffmpeg returned no audio")
    return wav


async def async_run_audio_pipeline(
    hass: HomeAssistant,
    *,
    pipeline: PipelineSettings,
    conversation_id: str,
    wav: bytes,
    language: str | None = None,
    timeout: float = VOICE_TIMEOUT,
) -> PipelineReply:
    """Run STT and the conversation agent of a pipeline on WAV audio.

    ``assist_pipeline`` is imported lazily: the package must stay importable
    without its heavy dependencies.
    """
    if not pipeline.stt_engine:
        raise VoiceNotConfiguredError("the pipeline has no speech-to-text engine")

    from homeassistant.components import assist_pipeline
    from homeassistant.components.stt import (
        AudioBitRates,
        AudioChannels,
        AudioCodecs,
        AudioFormats,
        AudioSampleRates,
        SpeechMetadata,
    )

    speech = ""
    stt_text = ""
    new_conversation_id: str | None = None

    @callback
    def _on_event(event: assist_pipeline.PipelineEvent) -> None:
        nonlocal speech, stt_text, new_conversation_id
        data = event.data or {}
        if event.type == assist_pipeline.PipelineEventType.STT_END:
            output = data.get("stt_output")
            if isinstance(output, dict) and isinstance(output.get("text"), str):
                stt_text = output["text"]
        elif event.type == assist_pipeline.PipelineEventType.INTENT_END:
            output = data.get("intent_output")
            if not isinstance(output, dict):
                return
            speech = extract_speech({"response": output.get("response")})
            raw_id = output.get("conversation_id")
            if isinstance(raw_id, str) and raw_id:
                new_conversation_id = raw_id

    metadata = SpeechMetadata(
        language=language or pipeline.stt_language or pipeline.language,
        format=AudioFormats.WAV,
        codec=AudioCodecs.PCM,
        bit_rate=AudioBitRates.BITRATE_16,
        sample_rate=AudioSampleRates.SAMPLERATE_16000,
        channel=AudioChannels.CHANNEL_MONO,
    )

    async with asyncio.timeout(timeout):
        await assist_pipeline.async_pipeline_from_audio_stream(
            hass,
            context=Context(),
            event_callback=_on_event,
            stt_metadata=metadata,
            stt_stream=_async_chunks(wav),
            pipeline_id=pipeline.id,
            conversation_id=conversation_id,
            start_stage=assist_pipeline.PipelineStage.STT,
            end_stage=assist_pipeline.PipelineStage.INTENT,
        )

    return PipelineReply(text=speech or stt_text, conversation_id=new_conversation_id)


async def async_stage_voice_reply(
    hass: HomeAssistant,
    pipeline: PipelineSettings,
    text: str,
    *,
    timeout: float = TTS_TIMEOUT,
) -> Path:
    """Synthesize ``text`` and stage it as an OGG/Opus voice note.

    The caller must delete the returned file after sending it.
    """
    if not pipeline.tts_engine:
        raise VoiceNotConfiguredError("the pipeline has no text-to-speech engine")

    from homeassistant.components import tts

    options: dict[str, str] = {}
    if pipeline.tts_voice:
        options[tts.ATTR_VOICE] = pipeline.tts_voice

    stream = tts.async_create_stream(
        hass,
        engine=pipeline.tts_engine,
        language=pipeline.tts_language,
        options=options,
    )
    stream.async_set_message(text)
    async with asyncio.timeout(timeout):
        native = b"".join([chunk async for chunk in stream.async_stream_result()])
    if not native:
        raise HomeAssistantError("text-to-speech returned no audio")

    ogg = await _async_encode_ogg(hass, native)
    path = _staging_dir(hass) / f"answer_{uuid.uuid4().hex}.ogg"
    await hass.async_add_executor_job(_write_bytes, path, ogg)
    return path


async def async_transcode_and_maybe_keep(
    hass: HomeAssistant,
    source: Path,
    *,
    max_seconds: int,
    keep: bool = False,
) -> tuple[bytes, bool]:
    """Transcode a downloaded voice file and move it to the keep directory.

    Returns (wav_bytes, removed_or_moved). When ``keep`` is True the original
    file is moved to ``.storage/hearthkeeper/downloads/saved/`` instead of
    being deleted; the caller still needs to discard the WAV.
    """
    wav = await async_transcode_to_wav(hass, source, max_seconds=max_seconds)
    if keep:
        dest = _download_dir(hass, keep=True) / source.name
        await hass.async_add_executor_job(_move, source, dest)
        return wav, True
    return wav, False


async def async_discard_file(hass: HomeAssistant, path: Path) -> None:
    """Delete a staged file, ignoring a missing or locked path."""
    try:
        await hass.async_add_executor_job(_unlink, path)
    except OSError as err:
        _LOGGER.debug("Could not delete a staged audio file (%s)", type(err).__name__)


def _staging_dir(hass: HomeAssistant) -> Path:
    """Return a writable directory for temporary audio files.

    TTS reply files are written here and deleted after sending. The directory
    is inside ``.storage`` so it is never served over HTTP.
    """
    return Path(hass.config.path(".storage", STORAGE_DIR, "tmp"))


def _download_dir(hass: HomeAssistant, keep: bool = False) -> Path:
    """Return the directory where incoming voice files are stored.

    When ``keep`` is True the file is not deleted after processing.
    """
    return Path(
        hass.config.path(".storage", STORAGE_DIR, "saved" if keep else "tmp")
    )


async def _async_encode_ogg(hass: HomeAssistant, audio: bytes) -> bytes:
    """Encode any audio container into OGG/Opus for Telegram."""
    ffmpeg = await _async_which(hass, "ffmpeg")
    if ffmpeg is None:
        raise HomeAssistantError("ffmpeg is not installed")

    ogg = await _async_run(
        ffmpeg,
        [
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            "pipe:0",
            "-vn",
            "-ac",
            "1",
            "-ar",
            "48000",
            "-c:a",
            "libopus",
            "-b:a",
            "32k",
            "-application",
            "voip",
            "-f",
            "ogg",
            "pipe:1",
        ],
        stdin=audio,
    )
    if not ogg:
        raise HomeAssistantError("ffmpeg returned no audio")
    return ogg


async def _async_duration(hass: HomeAssistant, source: Path) -> float | None:
    """Return the audio duration in seconds, when ffprobe is available."""
    ffprobe = await _async_which(hass, "ffprobe")
    if ffprobe is None:
        return None
    try:
        output = await _async_run(
            ffprobe,
            [
                "-v",
                "error",
                "-show_entries",
                "format=duration",
                "-of",
                "default=nw=1:nk=1",
                str(source),
            ],
        )
    except HomeAssistantError:
        # Let ffmpeg report the real decoding error.
        return None

    try:
        return float(output.strip())
    except ValueError:
        return None


async def _async_which(hass: HomeAssistant, name: str) -> str | None:
    """Locate a binary without blocking the event loop."""
    return await hass.async_add_executor_job(shutil.which, name)


async def _async_run(
    binary: str,
    args: list[str],
    *,
    stdin: bytes | None = None,
    timeout: float = MEDIA_TIMEOUT,
) -> bytes:
    """Run a media tool and return its stdout."""
    process = await asyncio.create_subprocess_exec(
        binary,
        *args,
        stdin=asyncio.subprocess.PIPE,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    try:
        async with asyncio.timeout(timeout):
            stdout, stderr = await process.communicate(stdin)
    except TimeoutError:
        process.kill()
        await process.wait()
        raise HomeAssistantError(f"{Path(binary).name} timed out") from None

    if process.returncode != 0:
        # stderr may contain the file name only, never the audio itself.
        _LOGGER.debug(
            "%s failed with code %s: %s",
            Path(binary).name,
            process.returncode,
            stderr.decode("utf-8", "replace")[:300],
        )
        raise HomeAssistantError(f"{Path(binary).name} failed")
    return stdout


async def _async_chunks(data: bytes) -> AsyncIterator[bytes]:
    """Split audio into pipeline-sized chunks."""
    for start in range(0, len(data), _CHUNK_SIZE):
        yield data[start : start + _CHUNK_SIZE]


def _write_bytes(path: Path, data: bytes) -> None:
    """Write a staged file, creating its directory."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _unlink(path: Path) -> None:
    """Delete a file if it still exists."""
    path.unlink(missing_ok=True)


def _move(source: Path, dest: Path) -> None:
    """Move source to dest, creating parent directories."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(source), str(dest))


